LOCALES = {"ru": RU}

def tr(key: str, lang: str = "ru", **kwargs) -> str:
    d = LOCALES.get(lang, RU)
    s = d.get(key, RU.get(key, key))
    safe_kwargs = {k: html.escape(f"{v:,}".replace(",", " ") if isinstance(v, int) else str(v), quote=False) for k, v in kwargs.items()}
    return s.format(**safe_kwargs)
